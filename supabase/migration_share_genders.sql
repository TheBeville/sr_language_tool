-- ====================================================================
-- Migration: Share Genders Across Languages & Deduplicate Existing Genders
-- ====================================================================
-- This migration converts the 1:N language->gender relationship into a
-- Many-to-Many (N:M) relationship via a new `language_genders` junction table.
-- It also deduplicates existing genders per user and links existing
-- languages to the canonical gender records.
-- ====================================================================

BEGIN;

-- --------------------------------------------------------------------
-- 1. Create the junction table: language_genders
-- --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.language_genders (
  sync_id          UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  id               BIGINT      GENERATED BY DEFAULT AS IDENTITY,
  user_id          UUID        NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  language_sync_id UUID        NOT NULL REFERENCES public.languages(sync_id) ON DELETE CASCADE,
  gender_sync_id   UUID        NOT NULL REFERENCES public.genders(sync_id) ON DELETE CASCADE,
  last_modified    TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_language_gender UNIQUE (language_sync_id, gender_sync_id)
);

-- --------------------------------------------------------------------
-- 2. Populate language_genders using canonical (deduplicated) genders
-- --------------------------------------------------------------------
-- For each user and gender string (case-insensitive), pick one canonical sync_id.
WITH canonical_genders AS (
  SELECT DISTINCT ON (user_id, LOWER(TRIM(gender)))
    sync_id AS canonical_sync_id,
    user_id,
    LOWER(TRIM(gender)) AS norm_gender
  FROM public.genders
  ORDER BY user_id, LOWER(TRIM(gender)), last_modified ASC, sync_id ASC
),
existing_associations AS (
  SELECT
    g.user_id,
    g.language_sync_id,
    c.canonical_sync_id AS gender_sync_id,
    MAX(g.last_modified) AS last_modified
  FROM public.genders g
  JOIN canonical_genders c
    ON g.user_id = c.user_id
   AND LOWER(TRIM(g.gender)) = c.norm_gender
  GROUP BY g.user_id, g.language_sync_id, c.canonical_sync_id
)
INSERT INTO public.language_genders (
  sync_id,
  user_id,
  language_sync_id,
  gender_sync_id,
  last_modified
)
SELECT
  gen_random_uuid(),
  user_id,
  language_sync_id,
  gender_sync_id,
  last_modified
FROM existing_associations
ON CONFLICT (language_sync_id, gender_sync_id) DO NOTHING;

-- --------------------------------------------------------------------
-- 3. Delete non-canonical (duplicate) rows from public.genders
-- --------------------------------------------------------------------
WITH canonical_genders AS (
  SELECT DISTINCT ON (user_id, LOWER(TRIM(gender)))
    sync_id AS canonical_sync_id
  FROM public.genders
  ORDER BY user_id, LOWER(TRIM(gender)), last_modified ASC, sync_id ASC
)
DELETE FROM public.genders
WHERE sync_id NOT IN (SELECT canonical_sync_id FROM canonical_genders);

-- --------------------------------------------------------------------
-- 4. Clean up gender text (trim whitespace)
-- --------------------------------------------------------------------
UPDATE public.genders
SET gender = TRIM(gender);

-- --------------------------------------------------------------------
-- 5. Drop language_sync_id from public.genders
-- --------------------------------------------------------------------
ALTER TABLE public.genders
  DROP COLUMN IF EXISTS language_sync_id;

-- --------------------------------------------------------------------
-- 6. Add unique constraint so duplicate genders cannot be created per user
-- --------------------------------------------------------------------
CREATE UNIQUE INDEX IF NOT EXISTS uq_genders_user_gender_lower
  ON public.genders (user_id, LOWER(gender));

-- --------------------------------------------------------------------
-- 7. Configure Row Level Security (RLS) on language_genders
-- --------------------------------------------------------------------
ALTER TABLE public.language_genders ENABLE ROW LEVEL SECURITY;

DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE tablename = 'language_genders'
      AND policyname = 'users_own_language_genders'
  ) THEN
    CREATE POLICY "users_own_language_genders" ON public.language_genders
      FOR ALL USING (auth.uid() = user_id);
  END IF;
END $$;

COMMIT;
